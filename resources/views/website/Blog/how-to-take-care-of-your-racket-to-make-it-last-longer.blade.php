        <h4 class="text-color">Wipe Your Racket After Every Use</h4>
        <p>Sweat, dust and moisture look like a part of your daily play. These harmless parts of our daily life deteriorate the racket’s material, especially the grip, due to direct contact. You must clean your racket thoroughly after every playing session. Cleaning must be performed using a clean microfibre cloth while avoiding wet wipes or any other alcohol-based cleaners. As alcohol-based cleaners break down the protective coating of the racket grip, causing the deterioration of the material.</p>
        <h4 class="text-color">Inspect Strings and Frame</h4> 
        <p>Inspect the racket before and after every play, as this would help you to spot any problems at an early stage. A simple hand inspection can reveal changes in tension or fraying of strings. You can also spot any cracks in the frame with a brief look. This quick examination will help you spot the damage at an early stage, giving you enough time to fix it.</p>   
        <h4 class="text-color">Avoid Contact with the Ground</h4>
        <p>Smashing your racket on the net, tapping it on the court and scooping the ball or shuttlecocks will reduce the racket’s life. Every hard knock weakens the racket frame and strings on the grommets. The racket must be protected between points from hitting the ground directly.</p>
       <h4 class="text-color">Store in a Racket Bag</h4>
       <p>The racket must be stored in a padded racket bag right after the game. A structured bag with proper cushioning protects your racket from physical strain. A bag with thermal lining can be a priority as it provides a shield for your racket from humidity and sudden climate change.</p>
